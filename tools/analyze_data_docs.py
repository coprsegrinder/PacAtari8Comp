def first_sentence(t, n=150):
    s = re.split(r"(?<=[.;])\s", t, maxsplit=1)[0]
    return (s[:n - 3] + "...") if len(s) > n else s


def core_tables():
    """[(C name, comment)] of the data tables the core indexes, from core/tables.h"""
    out = []
    with open(TABLES_H, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    for i, l in enumerate(lines):
        m = re.match(r"^extern const uint8_t \*const (\w+);", l)
        if m and i > 0:
            c = re.match(r"^/\*\s*(.*?)\s*\*/", lines[i - 1])
            text = c.group(1) if c else ""
            if not text or text.startswith("the whole images"):                       # the three images have their comment on the `#define NAME_SIZE` line
                d = [re.search(r"/\*\s*(.*?)\s*\*/", x) for x in lines if x.startswith("#define %s_SIZE " % m.group(1))]
                prefix = "" if m.group(1) == "MAZE_DATA" else "the whole image (the tables above are slices of it): "
                text = (prefix + d[0].group(1)) if d and d[0] else text
            out.append((m.group(1), text))
    return out


def world_fields():
    with open(WORLD_H, encoding="utf-8") as fh:
        t = fh.read()
    return set(re.findall(r"\buint8_t\s+(\w+)(?:\[\d+\])?;", t))


def constants_in_header():
    with open(CONSTANTS_H, encoding="utf-8") as fh:
        t = fh.read()
    return {m.group(1): int(m.group(2)) for m in re.finditer(r"^#define (\w+) (\d+)\s", t, re.M)}


USED_NAMES = None


def used_names():
    """how many of the named constants appear in core/ and app/ (not counting constants.h itself)"""
    txt = ""
    for d in ("core", "app"):
        for fn in sorted(os.listdir(os.path.join(ROOT, "src", "c", d))):
            if fn.endswith((".c", ".h")) and fn != "constants.h":
                with open(os.path.join(ROOT, "src", "c", d, fn), encoding="utf-8") as fh:
                    txt += fh.read()
    return [n for n, *_ in C.NAMED if re.search(r"\b" + n + r"\b", txt)]


def facts():
    f = {}
    f["kinds"] = collections.Counter(z[3] for z in Z.ZP)
