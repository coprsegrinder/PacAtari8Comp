"""Stage 68 (communication): the chapter docs/46-communication.md, generated from the static sets of tools/comm_map.py, its evidence (analysis/evidence-comm-summary.txt) and the curated text of this file.
Usage: python -I tools/analyze_comm.py [--doc docs/46-communication.md]   (the evidence is written by tools/comm_map.py --write analysis/evidence-comm-summary.txt)"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.dirname(HERE)
import comm_map as K  # noqa: E402

EVIDENCE = os.path.join(ROOT, "analysis", "evidence-comm-summary.txt")
PREEMPT = {"key": "the vertical-blank handler (at any instruction) and the display-list handlers", "newgame": "the same: it runs in the main program's time, between interrupts",
           "vbi": "the display-list handlers (non-maskable); it does not interrupt itself (it ends within the frame, `38`)", "dli1": "nothing (an NMI is not interrupted by an NMI)", "dli2": "nothing"}
WHEN = {"key": "all the time the interrupts leave free, never returns", "newgame": "once per game: entered from the key loop (`$A541`, START), back to it (`$A4B6`)", "vbi": "once per frame (60 / s NTSC)",
        "dli1": "five times per game frame, at the band lines (`35`)", "dli2": "five times per title frame"}
ENTRY = {"key": "`$A4BA`", "newgame": "`$A477`", "vbi": "`$A5FD` (`VVBLKD`)", "dli1": "`$A573` (`VDSLST`)", "dli2": "`$A5CE` (`VDSLST`)"}


def catalogue():
    """-> {name: (address text, description)} from docs/25"""
    with open(os.path.join(ROOT, "docs", "25-variable-catalogue.md"), encoding="utf-8") as fh:
        t = fh.read()
    out = {}
    for m in re.finditer(r"^\| `(\$[0-9A-F]{2}(?:-\$[0-9A-F]{2})?)` \| ([A-Za-z0-9_]+)\*? \| \d+ \| [^|]* \| ([^|]*) \|", t, re.M):
        out.setdefault(m.group(2), (m.group(1), m.group(3).strip()))
    return out


def chapter():
    with open(EVIDENCE, encoding="utf-8") as fh:
        ev = fh.read()
    m = re.search(r"run: (\d+) contexts runs .*: (\d+) outside", ev)
    nruns, nbad = (m.group(1), m.group(2)) if m else ("?", "?")
    st = K.static_sets()
    sh = K.shared(st)
    cat = catalogue()
    names, mat = K.pair_matrix(sh)
    zp = {k[1]: v for k, v in sh.items() if k[0] == "zp"}
    mem = {k[1]: v for k, v in sh.items() if k[0] == "mem"}
    hand = {k: v for k, v in zp.items() if (v[0] | v[1]) & {"key", "dli1", "dli2"}}
    P = []
    w = P.append
    w("# 46 - Communication (stage 68)")
    w("")
    w("GENERATED by `python -I tools/comm_map.py --write analysis/evidence-comm-summary.txt` and `python -I tools/analyze_comm.py --doc docs/46-communication.md` from the static read / write sets of the contexts of the game (`tools/absint6502.py`, the names of `25`), their check on the concrete 6502 and the curated text of `tools/analyze_comm.py`; tests: `tests/test_comm.py`. What crosses the boundary of the machine is `45`; this chapter is the other half of the question: **the game does not communicate with anything outside the machine, and inside it the parts that run interleaved talk through a short, listed set of variables.**")
    w("")
    w("## 1. The result")
    w("")
    w("- **No communication with the outside, of any kind** (`45`, section 5): no file, device, serial-bus, modem or network access (no `CIO`, no `SIO`, no page 3, no serial data register, no PIA) and two OS calls (`SETVBV`, `XITVBV`). The cartridge is the only code; nothing is received but the 14 declared inputs. Stage 68 is a *measured* \"nothing\", not an assumption. **There is no multiplayer link either**: the second player is the same machine, taking turns (section 5).")
    w("- **Inside the program there are %d contexts on one CPU** (section 2): the key loop, the new-game sequence it starts, the vertical-blank handler (the whole game frame) and the two display-list handlers. They share **%d zero-page variables and %d memory regions** (section 3); **%d** of those variables are a hand-over between the key loop or a display-list handler and another context (section 4); the rest is the new game's clears and initialisations, which the frame handler then reads." % (len(K.CONTEXTS), len(zp), len(mem), len(hand)))
    w("- **The static sets were run, not only read** (section 6): %s runs of the contexts from random states on the concrete 6502; every cell below `$4000` read or written (outside the stack, the ROM and the accesses through a pointer, which `42` classifies) lies in the static set of its context: **%s outside**." % (nruns, nbad))
    w("- **For a port**: the display-list handlers only *read* what the frame handler and the key loop leave (5 and 2 variables) and touch the chips; in a port they are a per-band table of colours and character-set pages (`35`, section 4), with no communication to keep. The key loop is an **event poll** that writes %d variables and regions (section 4: `GameState`, `Paused`, `TwoPlayers`, `StartLevel`, the countdown and attract-mode variables, `IntroRequest`, `KeyDebounce`, `DliColors`). The frame handler is **one function call per frame** (`44`). A port that runs the poll and the frame in turn, between frames, carries the whole of the original's communication in section 4. The original interleaves them at any instruction; that this is harmless is the original's protocol (section 5), not something this stage proves (section 7)." % len(st["key"][1]))
    w("")
    w("## 2. The contexts")
    w("")
    w("| Context | Entry | Runs | Can be interrupted by | Instructions (with callees) | Reads | Writes |")
    w("|---|---|---|---|---|---|---|")
    for name, label, entry in K.CONTEXTS:
        rd, wr, n = st[name]
        w("| %s | %s | %s | %s | %d | %d | %d |" % (label, ENTRY[name], WHEN[name], PREEMPT[name], n, len(rd), len(wr)))
    w("")
    w("`Reads` / `Writes` count zero-page variables (the names of `25`; an indexed access counts its whole variable) and the memory regions of `42` that the context and every routine it calls can touch (accesses through a pointer are in `29` and `42`). The key loop and the new-game sequence are one thread of control (the key loop jumps to the sequence and the sequence jumps back); the frame handler and the two display-list handlers are the interrupts.")
    w("")
    w("## 3. What is shared")
    w("")
    w("Variables and regions that one context writes and another reads or writes. The number written by the row and read by the column:")
    w("")
    w("```")
    w("row/col".ljust(9) + "".join(n.rjust(8) for n in names))
    for a in names:
        w(a.ljust(9) + "".join(("%d" % mat[(a, b)] if a != b else "-").rjust(8) for b in names))
    w("```")
    w("")
    w("The large number in the `newgame` row is the **initialisation of a game and of a board**: the new-game sequence clears `$20-$3F` and the sound chip itself and calls `InitBoard`, which clears `$80-$FF` and loads `$80-$93` (`43`, section 4); the frame handler reads every game variable afterwards. It is a hand-over of the whole state, in one direction, before the first frame of the game acts on it (section 5).")
    w("")
    w("Shared memory regions (not zero page): %s." % ", ".join("`%s` (written by %s, read by %s)" % (k, "/".join(sorted(v[0])), "/".join(sorted(v[1])) or "none") for k, v in sorted(mem.items())))
    w("")
    w("## 4. The hand-over variables")
    w("")
    w("The variables the key loop or a display-list handler shares with another context (the new game's bulk initialisation left out):")
    w("")
    w("| Variable | Address | Written by | Read by | What it is |")
    w("|---|---|---|---|---|")
    for k in sorted(hand):
        wr, rd = hand[k]
        addr, desc = cat.get(k, ("", ""))
        w("| `%s` | %s | %s | %s | %s |" % (k, "`%s`" % addr if addr else "", ", ".join(sorted(wr)), ", ".join(sorted(rd)) or "-", desc.replace("|", "/")))
    w("")
    w("Reading it: the **keys** reach the frame handler through `GameState`, `Paused`, `TwoPlayers`, `StartLevel` and `IntroRequest` (set by the key loop, acted on by the frame handler); the **countdown** is shared both ways (`CountdownActive`, `CountdownTimer`); `KeyDebounce` is counted down by the frame handler and waited on by the key loop; **`DliColors`** are written by the key loop (the band colours, faded by `DRKMSK` / `COLRSH`) and read by the display-list handlers; `ItemColor`, written in the frame, is read by the first handler; `BandCounter` is the display-list handlers' own counter, cleared by the frame handler at its start and counted by the handlers.")
    w("")
    w("## 5. The protocol, and the second player")
    w("")
    w("- **Single bytes.** The hand-over variables of section 4 are one byte, or one byte per entry, written by a single store; on a 6502 a one-byte store cannot be seen half done. The multi-byte values (the pointers, the score, the timers of two bytes) are written and read inside the frame handler.")
    w("- **A new game is announced with a flag.** The key loop writes `IntroRequest` = 1 at START, runs the new-game sequence, and writes 2 at its end (`$A4B6`); the catalogue (`25`) says the frame routine begins the READY! intro when it sees 2 and clears it. The frame handler can run in between (the sequence takes frames). The measured sessions of `38` (219,987 frames, the start-ups among them) show no half-initialised frame, but **the interleaving of the sequence with the frame handler at every instruction was not run** (section 7).")
    w("- **Two players are not communication.** There is one machine, one stick port in use at a time (`STICK0,x`, x = the player on turn: `41`) and one display; the second player is the same game state with the per-player variables swapped (the `Player[2]` structure: `19`, `30`, `43`): `CurrentPlayer` is a variable of the frame handler, and the turn switch swaps the maze between `$0C00`, `$1000` and `$1400` (`SavedMaze1`, `SavedMaze2`). No second machine, no link, no network play, nothing sent anywhere; the high score is a status line, lost at power-off (no cartridge RAM, no disk).")
    w("")
    w("## 6. The check on the machine")
    w("")
    w("```")
    for ln in ev.splitlines():
        if ln.startswith("run:") or ln.startswith("  ("):
            w(ln)
    w("```")
    w("")
    w("`tools/comm_map.py` runs each context from random states (the set-ups of `tools/iface_map.py`: the frame in six kinds and the running-game frame body, both display-list handlers, a pass of the key loop) with a probe on every read and write below `$4000`; `CurrentPlayer` is kept to 0 or 1. A pass of the key loop that starts a new game is checked against the key loop's and the sequence's sets together. The indexed clears of the new game and of `InitBoard` (`sta $20,x`, `$A47B`; `sta $80,x`, `$ADB4`; `$ADE3`) are given their spans from the code (`ldx #$1F`, `ldx #$7F`, `ldx #$13`); every other indexed zero-page access stayed inside the variable of its base address in the runs.")
    w("")
    w("## 7. Limits")
    w("")
    w("- **No race-freedom proof.** The protocol of section 5 is read from the code and the catalogue and seen in measured sessions; the check here shows what each context can touch, not that every interleaving of the new-game sequence with a frame gives the same game. A port that runs the key loop and the frame in two threads needs that proof; a port that runs them in turn does not.")
    w("- **A sample of states**: the dynamic check is a sample (as in `45`); the static sets are the claim.")
    w("- **The key loop is the original's**: a port's keyboard, console and joystick events replace it through the `Platform` of `45`; the variables of section 4 are the contract.")
    w("")
    return "\n".join(P) + "\n"


def main():
    if "--doc" in sys.argv:
        with open(os.path.join(ROOT, sys.argv[sys.argv.index("--doc") + 1]), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(chapter())
    else:
        print(chapter())


if __name__ == "__main__":
    main()
