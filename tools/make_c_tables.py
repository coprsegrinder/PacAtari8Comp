"""Stage 75a, reworked 2026-11-22: writes src/c/core/tables.h and tables.c: WHERE the data tables of the core are, and no byte of them.
The tables are slices of two images - the RAM tables `Start` builds at $0600-$07FF (512 bytes) and the ROM window $BA00-$BFFF (1,536 bytes) - plus the 920-byte maze `Start` expands to $0800.  The bytes are
not in the sources: the port installs them at start-up from the owner's ROM through the asset blob (src/c/assets: rom_install.c writes the blob, assets_boot() hands the three images to `tables_set`).
Until they are installed every table reads as zero and `tables_ready()` is 0; the test programs refuse to run then.
The layout is tools/core_tables.py (TABLES, IMAGES), the same list the Python port uses; tests/test_c_world.py compares the installed C tables with the Python ones, derived from the ROM by other code.
Usage: python -I tools/make_c_tables.py"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import make_core_tables as MT  # noqa: E402

ALL = list(MT.TABLES) + list(MT.IMAGES)
RAM_BASE, RAM_SIZE = 0x0600, 0x200
ROM_BASE, ROM_SIZE = 0xBA00, 0x600
MAZE_SIZE = 920


def header():
    L = ['/* GENERATED by tools/make_c_tables.py (stage 75a, reworked 2026-11-22): where the data tables of the core are.  Do not edit.  Contains no byte of the ROM:',
         ' * the bytes are installed at start-up from the owner\'s ROM (assets/rom_install.c writes the asset blob, assets_boot() calls tables_set). */',
         '#ifndef PM_CORE_TABLES_H',
         '#define PM_CORE_TABLES_H',
         '',
         '#include <stddef.h>',
         '#include <stdint.h>',
         '',
         '#define RAM_0600_SIZE %du   /* $%04X: the tables `Start` builds in RAM from the nibble stream */' % (RAM_SIZE, RAM_BASE),
         '#define ROM_BA00_SIZE %du  /* $%04X: the ROM window the core indexes into */' % (ROM_SIZE, ROM_BASE),
         '#define MAZE_DATA_SIZE %du  /* the maze `Start` expands to $0800 */' % MAZE_SIZE,
         '']
    for n, s, a, c, why in ALL:
        if n in ("RAM_0600", "ROM_BA00"):
            continue
        L.append('/* %s $%04X, %d bytes: %s */' % (s.upper(), a, c, why))
        L.append('extern const uint8_t *const %s;' % n)
    L += ['',
          '/* the whole images: the tables above are slices of them */',
          'extern const uint8_t *const RAM_0600;',
          'extern const uint8_t *const ROM_BA00;',
          'extern const uint8_t *const MAZE_DATA;',
          '',
          '/* install the three images (copied); 0 when the sizes are right, 1 when not (nothing is installed then) */',
          'int tables_set(const uint8_t *ram_0600, size_t ram_n, const uint8_t *rom_ba00, size_t rom_n, const uint8_t *maze, size_t maze_n);',
          '/* 1 once tables_set has succeeded */',
          'int tables_ready(void);',
          '',
          '/* one data table of the core: its name, where its bytes are, and the 6502 address they were read from */',
          'typedef struct TableInfo {',
          '    const char *name;',
          '    const uint8_t *data;',
          '    uint16_t count;',
          '    uint16_t addr;   /* address in the 6502 memory the table was read from */',
          '    uint8_t is_rom;  /* 1 = ROM, 0 = RAM expanded by Start */',
          '} TableInfo;',
          '',
          '#define PM_TABLE_COUNT %d' % len(ALL),
          'extern const TableInfo table_info[PM_TABLE_COUNT];',
          '',
          'uint8_t table_ram(uint16_t addr);  /* a byte of RAM_0600 by its address ($0600-$07FF) */',
          'uint8_t table_rom(uint16_t addr);  /* a byte of ROM_BA00 by its address ($BA00-$BFFF) */',
          '',
          '#endif', '']
    return "\n".join(L)


def source():
    L = ['/* GENERATED by tools/make_c_tables.py (stage 75a, reworked 2026-11-22).  Do not edit.  Contains no byte of the ROM. */',
         '#include "tables.h"',
         '',
         '#include <string.h>',
         '',
         'static uint8_t ram_store[RAM_0600_SIZE];',
         'static uint8_t rom_store[ROM_BA00_SIZE];',
         'static uint8_t maze_store[MAZE_DATA_SIZE];',
         'static int ready;',
         '']
    for n, s, a, c, why in ALL:
        if n in ("RAM_0600", "ROM_BA00"):
            continue
        base, store, store_base = ("ram_store", "ram_store", RAM_BASE) if s == "ram" else ("rom_store", "rom_store", ROM_BASE)
        assert store_base <= a and a + c <= store_base + (RAM_SIZE if s == "ram" else ROM_SIZE), n
        L.append('const uint8_t *const %s = %s + %d;' % (n, store, a - store_base))
    L += ['const uint8_t *const RAM_0600 = ram_store;',
          'const uint8_t *const ROM_BA00 = rom_store;',
          'const uint8_t *const MAZE_DATA = maze_store;',
          '',
          'int tables_set(const uint8_t *ram_0600, size_t ram_n, const uint8_t *rom_ba00, size_t rom_n, const uint8_t *maze, size_t maze_n)',
          '{',
          '    if (ram_0600 == NULL || rom_ba00 == NULL || maze == NULL || ram_n != RAM_0600_SIZE || rom_n != ROM_BA00_SIZE || maze_n != MAZE_DATA_SIZE) {',
          '        return 1;',
          '    }',
          '    memcpy(ram_store, ram_0600, RAM_0600_SIZE);',
          '    memcpy(rom_store, rom_ba00, ROM_BA00_SIZE);',
          '    memcpy(maze_store, maze, MAZE_DATA_SIZE);',
          '    ready = 1;',
          '    return 0;',
          '}',
          '',
          'int tables_ready(void)',
          '{',
          '    return ready;',
          '}',
          '',
          'const TableInfo table_info[PM_TABLE_COUNT] = {']
    for n, s, a, c, why in ALL:
        store, store_base = ("ram_store", RAM_BASE) if s == "ram" else ("rom_store", ROM_BASE)
        L.append('    {"%s", %s + %d, %d, 0x%04X, %d},' % (n, store, a - store_base, c, a, 1 if s == "rom" else 0))
    L += ['};', '',
          'uint8_t table_ram(uint16_t addr)', '{', '    return ram_store[addr - 0x0600u];', '}', '',
          'uint8_t table_rom(uint16_t addr)', '{', '    return rom_store[addr - 0xBA00u];', '}', '']
    return "\n".join(L)


def main():
    d = os.path.join(ROOT, "src", "c", "core")
    for name, text in (("tables.h", header()), ("tables.c", source())):
        with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("wrote src/c/core/tables.h, tables.c,", len(ALL), "tables (layout only)")


if __name__ == "__main__":
    main()
