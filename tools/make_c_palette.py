"""Stage 80b: writes src/c/render/palette.h and palette.c from analysis/palette-ntsc-measured.txt (tools/measure_palette.py: the 128 colours of the GTIA as Altirra 4.40 renders them, NTSC).
The low bit of a colour byte is not used by the GTIA, so the odd entries repeat the even ones.  NTSC only (owner, 2026-11-22).
Usage: python -I tools/make_c_palette.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "analysis", "palette-ntsc-measured.txt")


def read():
    pal = {}
    with open(SRC, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            k, r, g, b = line.split()
            pal[int(k, 16)] = (int(r), int(g), int(b))
    assert sorted(pal) == list(range(0, 256, 2)), "the measurement must hold all 128 colours"
    assert len(set(pal.values())) == 128
    return pal


def header():
    return """/* GENERATED by tools/make_c_palette.py (stage 80b): the NTSC palette as measured from Altirra 4.40 (analysis/palette-ntsc-measured.txt).  Do not edit.  NTSC only. */
#ifndef PM_RENDER_PALETTE_H
#define PM_RENDER_PALETTE_H

#include <stdint.h>

/* the red, green and blue of a GTIA colour byte (hue in the high nibble, luminance in the low; bit 0 is not used) */
extern const uint8_t NTSC_PALETTE[256][3];

#endif
"""


def source():
    pal = read()
    L = ['/* GENERATED by tools/make_c_palette.py (stage 80b).  Do not edit. */', '#include "palette.h"', '', 'const uint8_t NTSC_PALETTE[256][3] = {']
    for k in range(256):
        r, g, b = pal[k & 0xFE]
        L.append("    {%d, %d, %d},   /* $%02X */" % (r, g, b, k))
    L += ['};', '']
    return "\n".join(L)


def main():
    d = os.path.join(ROOT, "src", "c", "render")
    for name, text in (("palette.h", header()), ("palette.c", source())):
        with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("wrote src/c/render/palette.h, palette.c")


if __name__ == "__main__":
    main()
