r"""OV-68: writes tools/altirra_collide.cmd, the Altirra debugger harness of the collision audit: it assembles tools/collide_stub.s (ca65 / ld65 of external-tools/cc65), pokes it into free RAM of the EMULATED machine,
starts the game, and from the first frame of play on replaces the frame body by the stub: every frame a random scene of the five objects (the missile page and the four player pages, eight positions) is put on the
screen, the sixteen GTIA collision registers the scene produced are read (as the CPU reads them), and the scene and the registers are dumped to the log.  Nothing of the game's code or data is changed except the player-missile
pages, the eight position registers and HITCLR, the test aid being the skipped frame body.
Usage: python -I tools/make_collide_cmd.py [--seed 1..6] [--screen] [--wide] [--tall]     (--screen: the test screen, run 4; --wide: base x anywhere, run 5; --wide --tall: rows anywhere too, run 6)     then
  powershell -File tools\run_patrol_trace.ps1 -Log analysis\raw-logs\collide-1.txt -Seconds 60 -Cmd altirra_collide.cmd      and      python -I tools/analyze_collide.py analysis/raw-logs/collide-s*.txt"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CA65 = os.path.join(ROOT, "external-tools", "cc65", "bin", "ca65.exe")
LD65 = os.path.join(ROOT, "external-tools", "cc65", "bin", "ld65.exe")
ORG = 0x4200
MODES = {4: 1, 5: 2, 6: 6}                 # the stub's MODE byte by run (1 test screen, 2 wide base x); the other runs 0
SEEDS = {1: 0x5AA5, 2: 0x1234, 3: 0xC0DE, 4: 0x7B3F, 5: 0x2468, 6: 0xACE1}      # the seed of the stub's random generator, by run: logs are analysis/raw-logs/collide-s<N>.txt


def assemble():
    with tempfile.TemporaryDirectory() as d:
        o, lst, cfg, binf = (os.path.join(d, n) for n in ("s.o", "s.lst", "s.cfg", "s.bin"))
        with open(cfg, "w") as fh:
            fh.write("MEMORY { RAM: start = $%04X, size = $0400, file = %%O; }\nSEGMENTS { CODE: load = RAM, type = ro; }\n" % ORG)
        subprocess.run([CA65, "-o", o, "-l", lst, os.path.join(HERE, "collide_stub.s")], check=True)
        subprocess.run([LD65, "-C", cfg, "-o", binf, o], check=True)
        with open(binf, "rb") as fh:
            code = fh.read()
        with open(lst) as fh:
            m = re.search(r"^([0-9A-F]{6})\s+\d+\s+done:", fh.read(), re.M)
    return code, int(m.group(1), 16)


def main():
    n = int(sys.argv[sys.argv.index("--seed") + 1]) if "--seed" in sys.argv else 1
    if n in MODES and "--screen" not in sys.argv and "--wide" not in sys.argv:
        sys.argv += {1: ["--screen"], 2: ["--wide"], 6: ["--wide", "--tall"]}[MODES[n]]
    seed = SEEDS[n]
    code, done = assemble()
    pokes = ["f $4000 L$200 0"]
    for i in range(0, len(code), 16):
        pokes.append("eb $%04X %s" % (ORG + i, " ".join("$%02X" % b for b in code[i:i + 16])))
    pokes.append("eb $4084 $%02x $%02x" % (seed & 255, seed >> 8))
    mode = (1 if "--screen" in sys.argv else 0) | (2 if "--wide" in sys.argv else 0) | (4 if "--tall" in sys.argv else 0)
    if mode:
        pokes.append("eb $4086 %d" % mode)       # 1: the test screen (every character code in the maze band); 2: base x anywhere (the visible area of the objects)
    L = ["# OV-68: collision registers against random scenes, in the real game (GENERATED by tools/make_collide_cmd.py from tools/collide_stub.s; do not edit).",
         "# TEST AID (emulated machine only): from the first frame of play the frame body is skipped and each frame a random scene of the eight players / missiles is put on the screen by a stub in free RAM ($4200-$43FF, staging $4000-$40FF, record $4100-$41FF);",
         "# the collision registers the scene produced are read by the CPU and dumped with the scene.  Run (project root):  powershell -File tools/run_patrol_trace.ps1 -Log analysis/raw-logs/collide-s<N>.txt -Seconds 60 -Cmd altirra_collide.cmd",
         "# then:  python -I tools/analyze_collide.py analysis/raw-logs/collide-s*.txt",
         # the stub is poked when the key loop is first reached: the emulated machine's RAM is cleared by the cold start that follows the batch
         'bp -n a504 "r pc $a537; bc 0; %s"' % "; ".join(pokes),
         "r @t9 0",
         'bp -n a82c "r @t9 1"',
         "r @t8 0",
         # the stub takes up to 33,000 cycles (more than a frame): it runs in every third frame; in the others the frame body is skipped too
         'bp -n a603 "r @t8 (@t8+1)%3; r pc $a603+(@t9=1)*(($4200-$a603)*(@t8=0)+($a60d-$a603)*(@t8>0))"',
         'bp -n %x "db $4100 L$90; db $41a0 L4"' % done,
         'bp -n %x "db $4200 L20; db $0c00 L$400; db $3000 L$400; db $e000 L$200; db $2c0 L10; db $26f L1; bc 4"' % done]
    path = os.path.join(HERE, "altirra_collide.cmd")
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", path, len(code), "bytes of stub, seed $%04X, done at $%04X" % (seed, done))


if __name__ == "__main__":
    main()
