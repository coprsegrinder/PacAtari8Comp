"""Stage 80a (second part): writes src/c/assets/rom_layout.h and rom_layout.c: WHERE the data is in the cartridge, and nothing of the cartridge itself.
The C port installs its assets from the owner's own ROM (src/c/assets/rom_install.c): it checks the ROM (NTSC Pac-Man, 8,192 bytes, the sha256 below), cuts out the 79 regions that are not code, expands
the compressed pictures and tables, and writes the asset blob.  So this file holds the layout (name, address, size, kind of each region; the sha256 and size of the ROM to accept) and the 64 glyphs of the open
font (SIL OFL 1.1, third-party/, not part of the ROM), and no byte of the ROM.
The layout comes from tools/asset_pack.py (itself from tools/labels.py, checked against the ROM by tools/check_assets.py).  Only the NTSC cartridge is supported: there is no PAL data.
Usage: python -I tools/make_c_rom_layout.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import asset_pack as AP  # noqa: E402
import make_c_assets as MA  # noqa: E402


def header(P):
    return """/* GENERATED by tools/make_c_rom_layout.py (stage 80a): the layout of the data in the NTSC cartridge.  Do not edit.  Contains no byte of the ROM. */
#ifndef PM_ASSETS_ROM_LAYOUT_H
#define PM_ASSETS_ROM_LAYOUT_H

#include <stdint.h>

#define ROM_SIZE %du
#define ROM_BASE 0x%04Xu

extern const uint8_t ROM_SHA256[32];

/* one non-code region of the ROM: name, address, size and kind (generated by tools/make_c_rom_layout.py) */
typedef struct RomRegion {
    const char *name;
    uint16_t addr;      /* the address in the 6502 memory (the ROM is at $A000-$BFFF) */
    uint16_t size;
    uint8_t kind;       /* AssetKind: 0 data, 1 text (mode 2), 2 text (mode 6) */
} RomRegion;

#define ROM_REGION_COUNT %d
extern const RomRegion ROM_REGIONS[ROM_REGION_COUNT];

/* the 64 glyphs of the open font EightBit Atari-Regular (SIL OFL 1.1, third-party/EightBit-Atari-Fonts): the OS font page the text lines read, not part of the cartridge */
#define FONT_SIZE 512
extern const uint8_t FONT_DATA[FONT_SIZE];

#endif
""" % (P["rom"]["size"], 0xA000, len(P["regions"]))


def source(P):
    kinds = {n: k for _, _, k, n, _ in AP.labels.DATA}
    L = ['/* GENERATED by tools/make_c_rom_layout.py (stage 80a).  Do not edit.  Contains no byte of the ROM. */', '#include "rom_layout.h"', '',
         '/* sha256 of the NTSC Pac-Man cartridge image the port accepts */',
         'const uint8_t ROM_SHA256[32] = {']
    h = bytes.fromhex(P["rom"]["sha256"])
    for i in range(0, 32, 8):
        L.append("    " + ", ".join("0x%02X" % b for b in h[i:i + 8]) + ",")
    L += ['};', '', '/* in the order of the asset blob (tools/make_c_assets.py) */', 'const RomRegion ROM_REGIONS[ROM_REGION_COUNT] = {']
    for r in P["regions"]:
        L.append('    {"%s", 0x%s, %d, %d},' % (r["name"], r["addr"], r["size"], {"text6": 2, "text": 1}.get(kinds.get(r["name"]), 0)))
    L += ['};', '', '/* font: %s (c) 2018 Steve Boswell, SIL OFL 1.1, see third-party/README.md */' % "EightBit Atari-Regular", 'const uint8_t FONT_DATA[FONT_SIZE] = {']
    f = bytes.fromhex("".join(P["font"]["rows"]))
    assert len(f) == 512
    for i in range(0, 512, 16):
        L.append("    " + ", ".join("0x%02X" % b for b in f[i:i + 16]) + ",")
    L += ['};', '']
    return "\n".join(L)


def main():
    P = AP.build()
    assert MA.entries(P)[6][0].startswith("region.")
    d = os.path.join(ROOT, "src", "c", "assets")
    for name, text in (("rom_layout.h", header(P)), ("rom_layout.c", source(P))):
        with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("wrote src/c/assets/rom_layout.h, rom_layout.c:", len(P["regions"]), "regions")


if __name__ == "__main__":
    main()
