"""Stage 100 (long-term preservation and archival): makes the preservation archive of the whole project in build/archive/ and verifies that it restores.

  python -I tools/make_archive.py [--verify] [--write FILE]

The archive is a folder of a few big files, each with its SHA-256, so it can be copied to any storage and checked there:
  pacman-a8-history.bundle        the whole Git history (`git bundle --all`): every tracked file of every commit - the reconstructed source, the tools, the tests,
                                  the documentation, the evidence summaries, the third-party font with its licence
  pacman-a8-port-<v>-src.zip      the release archive of stage 99 (made fresh here from the committed tree)
  pacman-a8-owner-materials.zip   the ORIGINAL software and what the owner supplied: original/ (cartridge ROM, OS ROMs, the methodology list, the saved forum page),
                                  a800.zip. COPYRIGHTED, PRIVATE: never published (the release and the Git history do not contain them)
  pacman-a8-dependencies.zip      the downloads the project was built and measured with (external-tools/downloads: Altirra 4.40, cc65 snapshot) with their hashes
  pacman-a8-local-evidence.zip    the evidence that Git ignores and that is small enough to keep: emulator pictures, recordings, logs, session files, test aids
                                  (every ignored file below analysis/ and tools/ except raw-logs/)
  ARCHIVE-MANIFEST.json, SHA256SUMS, README-ARCHIVE.txt
NOT kept (and why): build/ (rebuilt), resources/ (derived from the ROM, rebuilt), external-tools/ extracted folders (unpacked from the downloads),
analysis/raw-logs/ (raw emulator debugger logs, regenerated by the tools/run_*.ps1 harnesses; about 8 GB), __pycache__, `Personal notes.txt` (the owner's, never archived).
Verification: every file against SHA256SUMS; the bundle verifies, clones, and its HEAD tree is the working tree; the release archive built from the CLONE has the
same SHA-256 as the one in the archive (the build is reproducible from the history alone); each zip's members equal the source files; `Personal notes.txt` appears nowhere."""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import make_release as R  # noqa: E402

OUT = os.path.join(ROOT, "build", "archive")
SKIP_PREFIX = ("build/", "resources/", "external-tools/", "analysis/raw-logs/", "original/", ".git/")
NEVER = ("Personal notes.txt",)
STAMP = (2026, 11, 24, 0, 0, 0)


def git(*a, cwd=ROOT):
    return subprocess.run(["git", *a], cwd=cwd, capture_output=True, text=True, check=True).stdout


def sha(path):
    return R.sha256(path)


def ignored_files():
    return [f for f in git("ls-files", "-o", "-i", "--exclude-standard").splitlines()
            if f and f not in NEVER and not f.startswith(SKIP_PREFIX) and "__pycache__" not in f and os.path.isfile(os.path.join(ROOT, f))]


def tree_files(top):
    out = []
    for d, _, fs in os.walk(os.path.join(ROOT, top)):
        for f in fs:
            out.append(os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, "/"))
    return sorted(out)


def write_zip(dest, files, prefix=""):
    """raw bytes (no line-end change: these are evidence), sorted, one time stamp"""
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in sorted(files):
            zi = zipfile.ZipInfo(prefix + f, STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            with open(os.path.join(ROOT, *f.split("/")), "rb") as fh:
                z.writestr(zi, fh.read(), compresslevel=6)
    return len(files)


def make():
    if git("status", "--porcelain").strip():
        sys.exit("the Git tree is not clean: commit first (the archive records the commit)")
    if os.path.exists(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    head = git("rev-parse", "HEAD").strip()
    parts = {}
    subprocess.run(["git", "bundle", "create", os.path.join(OUT, "pacman-a8-history.bundle"), "--all"], cwd=ROOT, check=True, capture_output=True)
    parts["pacman-a8-history.bundle"] = {"what": "git bundle --all", "commits": int(git("rev-list", "--count", "--all").strip())}
    rel = os.path.join(OUT, "%s-%s-src.zip" % (R.NAME, R.VERSION))
    man, _ = R.build_archive(rel)
    parts[os.path.basename(rel)] = {"what": "release archive (stage 99)", "files": len(man["files"]) + 1}
    own = tree_files("original") + [f for f in ("a800.zip",) if os.path.isfile(os.path.join(ROOT, f))]
    n = write_zip(os.path.join(OUT, "pacman-a8-owner-materials.zip"), own)
    parts["pacman-a8-owner-materials.zip"] = {"what": "original/ and a800.zip: copyrighted, private", "files": n}
    dep = tree_files("external-tools/downloads")
    n = write_zip(os.path.join(OUT, "pacman-a8-dependencies.zip"), dep)
    parts["pacman-a8-dependencies.zip"] = {"what": "external-tools/downloads", "files": n}
    ev = ignored_files()
    n = write_zip(os.path.join(OUT, "pacman-a8-local-evidence.zip"), ev)
    parts["pacman-a8-local-evidence.zip"] = {"what": "ignored evidence below analysis/ and tools/ (no raw-logs/)", "files": n}
    for k, v in parts.items():
        p = os.path.join(OUT, k)
        v["bytes"] = os.path.getsize(p)
        v["sha256"] = sha(p)
    roms = {}
    for n_ in R.ROMS:
        p = os.path.join(ROOT, "original", n_)
        if os.path.isfile(p):
            roms[n_] = sha(p)
    manifest = {"project": "Pac-Man (Atari 8-bit): preservation and C port", "git_head": head, "version": R.VERSION, "parts": parts, "original_roms_sha256": roms,
                "not_kept": ["build/", "resources/", "external-tools/ (extracted)", "analysis/raw-logs/", "Personal notes.txt"]}
    with open(os.path.join(OUT, "ARCHIVE-MANIFEST.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(manifest, fh, indent=1, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(OUT, "README-ARCHIVE.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(README.format(head=head, version=R.VERSION))
    names = sorted(f for f in os.listdir(OUT) if f != "SHA256SUMS")
    with open(os.path.join(OUT, "SHA256SUMS"), "w", encoding="utf-8", newline="\n") as fh:
        for f in names:
            fh.write("%s *%s\n" % (sha(os.path.join(OUT, f)), f))
    return manifest, ev, own, dep


README = """Pac-Man (Atari 8-bit) - preservation archive
============================================
Made from Git commit {head} (release version {version}).

Check:      sha256sum -c SHA256SUMS            (or: python -I tools/make_archive.py --verify, from a restored project)
Restore:    git clone pacman-a8-history.bundle pacman-a8        (the whole project and its history)
            unzip pacman-a8-owner-materials.zip -d pacman-a8    (the ROMs and the owner's reference files: PRIVATE, copyrighted)
            unzip pacman-a8-local-evidence.zip   -d pacman-a8    (evidence that Git ignores: pictures, recordings, logs)
            unzip pacman-a8-dependencies.zip     -d pacman-a8    (Altirra 4.40 and the cc65 snapshot, as downloaded)
Build:      docs/63-build-and-dependencies.md (recipe A: cmake, build, ctest), docs/65-release.md (the release),
            docs/64-testing-and-verification.md (how every claim was checked), docs/PROGRESS.md (the whole project's story).
The release archive pacman-a8-port-{version}-src.zip is the same file that tools/make_release.py makes from the cloned history.

Not in the archive, and how to get it back: build/ and resources/ are rebuilt; the unpacked tools in external-tools/ come from the zips;
analysis/raw-logs/ (about 8 GB of raw emulator logs) is regenerated by the tools/run_*.ps1 harnesses (the summaries that matter are in analysis/evidence-*-summary.txt, in Git).
The owner-materials zip is for the owner only. The release and the Git history contain no ROM.
"""


def verify(manifest, ev, own, dep, report):
    ok = True

    def step(name, good, detail=""):
        nonlocal ok
        ok = ok and good
        line = "%s  %s%s" % ("PASS" if good else "FAIL", name, ("  (" + detail + ")") if detail else "")
        print(line, flush=True)
        report.append(line)
    bad = []
    with open(os.path.join(OUT, "SHA256SUMS"), encoding="utf-8") as fh:
        sums = [l.rstrip("\n").split(" *", 1) for l in fh if l.strip()]
    for h, f in sums:
        if sha(os.path.join(OUT, f)) != h:
            bad.append(f)
    step("1 every file of the archive equals SHA256SUMS (%d files)" % len(sums), not bad and len(sums) == len(os.listdir(OUT)) - 1, ", ".join(bad))
    with tempfile.TemporaryDirectory() as tmp:
        b = os.path.join(OUT, "pacman-a8-history.bundle")
        v = subprocess.run(["git", "bundle", "verify", b], capture_output=True, text=True)
        step("2a the bundle verifies", v.returncode == 0, v.stderr.strip().splitlines()[-1] if v.returncode else "")
        clone = os.path.join(tmp, "clone")
        subprocess.run(["git", "clone", "-q", b, clone], check=True, capture_output=True)
        head = git("rev-parse", "HEAD", cwd=clone).strip()
        a = set(git("ls-files").splitlines())
        c = set(git("ls-files", cwd=clone).splitlines())
        step("2b the clone's HEAD is the recorded commit and tracks the same files (%d)" % len(c), head == manifest["git_head"] and a == c, head[:10])
        diff = [f for f in sorted(c) if R.content(os.path.join(ROOT, *f.split("/"))) != R.content(os.path.join(clone, *f.split("/")))]
        step("2c every tracked file of the clone equals the working tree (line ends aside)", not diff, ", ".join(diff[:3]))
        again = os.path.join(tmp, "again.zip")
        old_root = R.ROOT
        R.ROOT = clone
        try:
            R.build_archive(again)
        finally:
            R.ROOT = old_root
        rel = os.path.join(OUT, "%s-%s-src.zip" % (R.NAME, R.VERSION))
        step("3 the release archive built from the CLONE alone is byte-identical to the one in the archive", sha(again) == sha(rel), sha(rel)[:16])
    for zname, files in (("pacman-a8-owner-materials.zip", own), ("pacman-a8-dependencies.zip", dep), ("pacman-a8-local-evidence.zip", ev)):
        bad = []
        with zipfile.ZipFile(os.path.join(OUT, zname)) as z:
            members = z.namelist()
            for f in files:
                if sha(os.path.join(ROOT, *f.split("/"))) != hashlib_bytes(z.read(f)):
                    bad.append(f)
        step("4 %s: %d members equal their source files" % (zname, len(files)), not bad and sorted(members) == sorted(files), ", ".join(bad[:3]))
    leak = []
    for zname in ("pacman-a8-owner-materials.zip", "pacman-a8-dependencies.zip", "pacman-a8-local-evidence.zip", "%s-%s-src.zip" % (R.NAME, R.VERSION)):
        with zipfile.ZipFile(os.path.join(OUT, zname)) as z:
            leak += [zname + ":" + n for n in z.namelist() if n.endswith("Personal notes.txt")]
    step("5 `Personal notes.txt` is in no archive part", not leak, ", ".join(leak))
    roms = manifest["original_roms_sha256"]
    step("6 the manifest records the SHA-256 of the %d original ROMs" % len(roms), len(roms) == 3)
    return ok


def hashlib_bytes(b):
    return hashlib.sha256(b).hexdigest()


def main():
    a = sys.argv[1:]
    write = a[a.index("--write") + 1] if "--write" in a else None
    manifest, ev, own, dep = make()
    report = ["archive of commit %s in build/archive/" % manifest["git_head"]]
    for k, v in sorted(manifest["parts"].items()):
        report.append("  %-44s %12d bytes  sha256 %s" % (k, v["bytes"], v["sha256"][:16]))
    print("\n".join(report), flush=True)
    ok = True
    if "--verify" in a:
        ok = verify(manifest, ev, own, dep, report)
        report.append("ALL PASSED" if ok else "FAILURES")
        print(report[-1])
    if write:
        with open(os.path.join(ROOT, write), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("Stage 100 (docs/66-preservation.md): the preservation archive made and verified (tools/make_archive.py)\n\n" + "\n".join(report) + "\n")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
