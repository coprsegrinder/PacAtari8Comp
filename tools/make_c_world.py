"""Stage 75a: writes src/c/core/world.h and world.c, the World of the port-form core in C (docs/44, docs/51 section 3).
The fields are the ones of tools/core_world.py (FIELDS = the 181 zero-page variables of docs/25, plus the maze, the status rows, the OS shadows, the sticks, the collision registers,
the player-missile pages, the positions and the picture buffers) and the load / store use the same address ranges and the same order as World.load / World.store.
A field is a member of `struct World`, so a misspelt name does not compile.  The chip-write log (`pokey`) is a bounded list with an overflow count.
Usage: python -I tools/make_c_world.py"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import core_world as W  # noqa: E402

POKEY_MAX = 4096

# name, memory address, size, comment, loaded from memory, stored to memory   (the order of World.store: the later range wins where two overlap)
EXTRA = [
    ("maze", 0x0C00, 0x400, "$0C00-$0FFF: the maze screen", 1, 1),
    ("status", 0x2000, 0x50, "$2000-$204F: the status rows", 1, 1),
    ("shadow", 0x0200, 0x100, "$0200-$02FF: the OS shadows (index = address - $0200)", 1, 1),
    ("stick", 0x0278, 4, "STICK0-3 ($0278): the joystick shadows, an input (stored after `shadow`)", 1, 1),
    ("collide", 0xD000, 0x10, "$D000-$D00F: the GTIA collision registers (M0PF .. P3PL), an input, never stored", 1, 0),
    ("pm", 0x2300, 0x500, "$2300-$27FF: the player-missile pages (the missile page, then players 0-3)", 1, 1),
    ("hpos", 0xD000, 8, "HPOSP0-3, HPOSM0-3 ($D000-$D007, write): the positions", 1, 1),
    ("picbuf", 0x0400, 0x20, "$0400-$041F: the picture buffers (Pac-Man's rows, the ghost being drawn)", 1, 1),
    ("maze_orig", 0x0800, 0x400, "$0800-$0BFF: the stored maze of a new board (written by Start, never again)", 1, 1),
    ("saved1", 0x1000, 0x400, "$1000-$13FF: player 1's maze while player 2 plays", 1, 1),
    ("saved2", 0x1400, 0x400, "$1400-$17FF: player 2's maze while player 1 plays", 1, 1),
    ("title", 0x1C00, 0x400, "$1C00-$1FFF: the title screen", 1, 1),
]


STATE_SIZE = sum(c for _, _, c in W.FIELDS) + sum(e[2] for e in EXTRA)


def header():
    L = ['/* GENERATED by tools/make_c_world.py (stage 75a): the World of the port-form core (docs/44, docs/51).  Do not edit. */',
         '#ifndef PM_CORE_WORLD_H',
         '#define PM_CORE_WORLD_H',
         '',
         '#include <stddef.h>',
         '#include <stdint.h>',
         '',
         '#define PM_POKEY_MAX %d' % POKEY_MAX,
         '',
         "/* the state of the game by name: every zero-page variable of docs/25 (a byte, or an array for a multi-byte one; the original address is in the comment) plus the regions of the original's memory that the core reads or writes */",
         'typedef struct World {']
    for n, a, c in W.FIELDS:
        L.append('    uint8_t %s%s; /* $%02X */' % (n, '' if c == 1 else '[%d]' % c, a))
    for n, a, c, why, ld, st in EXTRA:
        L.append('    uint8_t %s[%d]; /* %s */' % (n, c, why))
    L += ['    /* the sound-chip writes made so far, in order (address, value); `pokey_overflow` counts the writes that did not fit */',
          '    uint16_t pokey_addr[PM_POKEY_MAX];',
          '    uint8_t pokey_val[PM_POKEY_MAX];',
          '    uint32_t pokey_n;',
          '    uint32_t pokey_overflow;',
          '} World;',
          '',
          '/* a region of the 64 KB memory image that is a member of World */',
          'typedef struct WorldRegion {',
          '    const char *name;',
          '    uint16_t addr;   /* address in the image */',
          '    uint16_t count;  /* bytes */',
          '    size_t offset;   /* offsetof(World, member) */',
          '    uint8_t loaded;  /* world_load reads it */',
          '    uint8_t stored;  /* world_store writes it */',
          '} WorldRegion;',
          '',
          '#define PM_WORLD_ZP_FIELDS %d' % len(W.FIELDS),
          '#define PM_WORLD_REGIONS %d' % (len(W.FIELDS) + len(EXTRA)),
          '#define PM_STATE_SIZE %d   /* the packed state: every region in table order, the zero page first (256 bytes) */' % STATE_SIZE,
          '',
          '/* the regions in the order of World.load / World.store of tools/core_world.py: the zero-page fields by address, then maze, status, shadow, stick, collide, pm, hpos, picbuf */',
          'extern const WorldRegion world_regions[PM_WORLD_REGIONS];',
          '',
          'void world_init(World *w);                                   /* everything zero, the log empty */',
          'void world_load(World *w, const uint8_t mem[65536]);         /* World.load: also empties the log */',
          'void world_store(const World *w, uint8_t mem[65536]);        /* World.store: writes the regions marked `stored`, leaves the rest of `mem` alone */',
          'void world_pokey(World *w, uint16_t addr, uint8_t value);    /* appends one chip write to the log */',
          'void world_pack(const World *w, uint8_t out[PM_STATE_SIZE]); /* the whole state, every region (collide and hpos too) in table order: the vector files use it */',
          'void world_unpack(World *w, const uint8_t in[PM_STATE_SIZE]);/* the inverse; the log is emptied */',
          '',
          '#endif', '']
    return "\n".join(L)


def source():
    L = ['/* GENERATED by tools/make_c_world.py (stage 75a).  Do not edit. */',
         '#include "world.h"',
         '',
         '#include <string.h>',
         '',
         'const WorldRegion world_regions[PM_WORLD_REGIONS] = {']
    for n, a, c in W.FIELDS:
        L.append('    {"%s", 0x%04X, %d, offsetof(World, %s), 1, 1},' % (n, a, c, n))
    for n, a, c, why, ld, st in EXTRA:
        L.append('    {"%s", 0x%04X, %d, offsetof(World, %s), %d, %d},' % (n, a, c, n, ld, st))
    L += ['};',
          '',
          'void world_init(World *w)',
          '{',
          '    memset(w, 0, sizeof *w);',
          '}',
          '',
          'void world_load(World *w, const uint8_t mem[65536])',
          '{',
          '    size_t i;',
          '    for (i = 0; i < PM_WORLD_REGIONS; i++) {',
          '        const WorldRegion *r = &world_regions[i];',
          '        if (r->loaded) {',
          '            memcpy((uint8_t *)w + r->offset, mem + r->addr, r->count);',
          '        }',
          '    }',
          '    w->pokey_n = 0;',
          '    w->pokey_overflow = 0;',
          '}',
          '',
          'void world_store(const World *w, uint8_t mem[65536])',
          '{',
          '    size_t i;',
          '    for (i = 0; i < PM_WORLD_REGIONS; i++) {',
          '        const WorldRegion *r = &world_regions[i];',
          '        if (r->stored) {',
          '            memcpy(mem + r->addr, (const uint8_t *)w + r->offset, r->count);',
          '        }',
          '    }',
          '}',
          '',
          'void world_pack(const World *w, uint8_t out[PM_STATE_SIZE])',
          '{',
          '    size_t i, k = 0;',
          '    for (i = 0; i < PM_WORLD_REGIONS; i++) {',
          '        const WorldRegion *r = &world_regions[i];',
          '        memcpy(out + k, (const uint8_t *)w + r->offset, r->count);',
          '        k += r->count;',
          '    }',
          '}',
          '',
          'void world_unpack(World *w, const uint8_t in[PM_STATE_SIZE])',
          '{',
          '    size_t i, k = 0;',
          '    for (i = 0; i < PM_WORLD_REGIONS; i++) {',
          '        const WorldRegion *r = &world_regions[i];',
          '        memcpy((uint8_t *)w + r->offset, in + k, r->count);',
          '        k += r->count;',
          '    }',
          '    w->pokey_n = 0;',
          '    w->pokey_overflow = 0;',
          '}',
          '',
          'void world_pokey(World *w, uint16_t addr, uint8_t value)',
          '{',
          '    if (w->pokey_n < PM_POKEY_MAX) {',
          '        w->pokey_addr[w->pokey_n] = addr;',
          '        w->pokey_val[w->pokey_n] = value;',
          '        w->pokey_n++;',
          '    } else {',
          '        w->pokey_overflow++;',
          '    }',
          '}', '']
    return "\n".join(L)


def main():
    d = os.path.join(ROOT, "src", "c", "core")
    for name, text in (("world.h", header()), ("world.c", source())):
        with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("wrote src/c/core/world.h, world.c,", len(W.FIELDS), "zero-page fields")


if __name__ == "__main__":
    main()
