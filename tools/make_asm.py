"""Step C9: generate the full ca65 disassembly of Pac-Man.rom into src/asm/pacman.s.

Usage (project root):  python -I tools/make_asm.py
Code = recursive trace from the entry points below; everything else is emitted as .byte data
(data labelling is step C11). Each entry point has its evidence recorded here.
Read-only on the ROM; writes src/asm/pacman.s and src/asm/pacman.cfg.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import disasm6502 as D  # noqa: E402

ROOT = os.path.dirname(HERE)
BASE = 0xA000
data = open(os.path.join(ROOT, "original", "Pac-Man.rom"), "rb").read()

# address: (name, evidence)
ENTRIES = {
    0xA386: ("Start", "cartridge RUN vector at $BFFA"),
    0xA6B4: ("Init", "cartridge INIT vector at $BFFE (the routine is just RTS)"),
    0xA5FD: ("VbiHandler", "SETVBV (A=7 deferred VBI, X=$A5, Y=$FD) called at $A460; ends with JMP XITVBV at $A60D"),
    0xA573: ("DliHandler1", "VDSLST ($0200/$0201) set to $A573 via LDX #$A3/LDY #$73 -> JSR $A6B5 at $A49B (pushes A/X, ends RTI)"),
    0xA5CE: ("DliHandler2", "second routine in the same style (PHA/TXA/PHA/TYA/PHA ... RTI); bytes $A5CE-$A5FC lie between the DLI and VBI handlers. "
                           "How it is installed is still to be confirmed."),
}
# Named routines/addresses found as call targets (not entry points).
EXTRA_NAMES = {0xA6B5: "SetDisplayList"}
OS_NAMES = {0xE456: "CIOV", 0xE459: "SIOV", 0xE45C: "SETVBV", 0xE45F: "SYSVBV", 0xE462: "XITVBV"}

code, targets = D.trace(data, BASE, list(ENTRIES))
names = {a: n for a, (n, _) in ENTRIES.items()}
names.update(EXTRA_NAMES)
names.update(OS_NAMES)

# Sanity: every in-ROM target must be the start of a traced instruction, or a label inside data is fine
# only if it is not in the middle of an instruction.
inside = set()
for a, n in code.items():
    inside.update(range(a + 1, a + n))
bad = sorted(t for t in targets if BASE <= t < BASE + len(data) and t in inside)
if bad:
    sys.exit("targets inside an instruction: " + " ".join("%04X" % t for t in bad))

used_os = sorted(t for t in targets if t in OS_NAMES)
out = os.path.join(ROOT, "src", "asm", "pacman.s")
with open(out, "w", newline="\n") as fh:
    fh.write("; Pac-Man (Atari 8-bit) -- disassembly of original/Pac-Man.rom, $A000-$BFFF, 8,192 bytes\n")
    fh.write("; GENERATED by tools/make_asm.py (step C9). Code comes from a recursive trace; the rest is\n")
    fh.write("; unlabelled data (step C11). Comments show address and original bytes.\n")
    fh.write("; Derived from copyrighted code: keep this repository private.\n\n")
    for a, (n, why) in sorted(ENTRIES.items()):
        fh.write("; %-12s $%04X  %s\n" % (n, a, why))
    fh.write("\n")
    for a in used_os:
        fh.write("%-8s = $%04X\n" % (OS_NAMES[a], a))
    fh.write('\n.segment "CODE"\n\n')
    D.listing(data, BASE, code, targets, names=names, out=fh)

with open(os.path.join(ROOT, "src", "asm", "pacman.cfg"), "w", newline="\n") as fh:
    fh.write("MEMORY { ROM: start = $A000, size = $2000, file = %O, fill = yes, fillval = $00; }\n")
    fh.write("SEGMENTS { CODE: load = ROM, type = ro; }\n")

covered = sum(code.values())
print("code: %d instructions, %d bytes (%.1f%%); data: %d bytes; targets: %d"
      % (len(code), covered, 100.0 * covered / len(data), len(data) - covered, len(targets)))
