"""Stage 66 / OV-67: writes tools/core_world.py, the `World` of the port-form core: every zero-page variable of the catalogue (docs/25) as a named attribute (an int, or a list for an array),
plus the maze screen `maze` ($0C00-$0FFF), the status rows `status` ($2000-$204F) and the list `pokey` of the sound-chip writes a function makes (address, value).
`World.load(mem)` / `World.store(mem)` convert from and to a 6502 memory image; tools/check_*.py use them to compare a port function with the ROM.
Usage: python -I tools/make_core_world.py"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import re  # noqa: E402
import analyze_state as S  # noqa: E402


def fields():
    t = S.read("docs/25-variable-catalogue.md")
    out, used = [], set()
    for m in re.finditer(r"^\| `\$([0-9A-F]{2})(?:-\$([0-9A-F]{2}))?` \| ([A-Za-z0-9_]+)\*? \| (\d+) \|", t, re.M):
        a, n = int(m.group(1), 16), int(m.group(4))
        if a in used:
            continue
        out.append((m.group(3), a, n))
        used.update(range(a, a + n))
    for a in range(256):
        if a not in used:
            out.append(("zp_%02X" % a, a, 1))
    return sorted(out, key=lambda f: f[1])


def main():
    F = fields()
    L = ['"""GENERATED by tools/make_core_world.py: the World of the port-form core (docs/44)."""', "",
         "FIELDS = (  # (name, zero-page address, count)"]
    for n, a, c in F:
        L.append("    (%r, 0x%02X, %d)," % (n, a, c))
    L += [")", "", "",
          "class World:",
          '    """the state of the game by name: every zero-page variable, the maze screen, the status rows, the player-missile pages and positions, and the sound-chip writes made so far"""',
          "",
          "    _EXTRA = ('maze', 'status', 'shadow', 'stick', 'collide', 'pokey', 'pm', 'hpos', 'picbuf', 'maze_orig', 'saved1', 'saved2', 'title')",
          "    _NAMES = frozenset(f[0] for f in FIELDS)",
          "",
          "    def __setattr__(self, name, value):",
          "        if name not in World._NAMES and name not in World._EXTRA:",
          "            raise AttributeError('World has no field ' + name)     # a misspelt name must not be silently dropped by store()",
          "        object.__setattr__(self, name, value)",
          "",
          "    def __init__(self):",
          "        for name, addr, n in FIELDS:",
          "            setattr(self, name, 0 if n == 1 else [0] * n)",
          "        self.maze = [0] * 0x400          # $0C00-$0FFF",
          "        self.status = [0] * 0x50         # $2000-$204F",
          "        self.shadow = [0] * 0x100        # $0200-$02FF: the OS shadows (index = address - $0200: GPRIOR $6F, STICK0 $78, PCOLR0-3 $C0-$C3, COLOR0-4 $C4-$C8 ...)",
          "        self.stick = [0] * 4             # STICK0-3 ($0278): the joystick shadows, an input",
          "        self.collide = [0] * 0x10        # $D000-$D00F: the GTIA collision registers (M0PF .. P3PL): an input",
          "        self.pokey = []                  # (register address, value) in the order written",
          "        self.pm = [0] * 0x500            # $2300-$27FF: the player-missile pages (the missile page, then players 0-3), one byte a scan line (OV-69)",
          "        self.hpos = [0] * 8              # HPOSP0-3, HPOSM0-3 ($D000-$D007, write): the positions of the players and missiles (OV-69)",
          "        self.picbuf = [0] * 0x20         # $0400-$041F: the picture buffers (Pac-Man's rows at $0400, the ghost being drawn at $0410) (OV-69)",
          "        self.maze_orig = [0] * 0x400     # $0800-$0BFF: the stored maze of a new board (written by Start, never again) (stage 78a)",
          "        self.saved1 = [0] * 0x400        # $1000-$13FF: player 1's maze while player 2 plays (stage 78a)",
          "        self.saved2 = [0] * 0x400        # $1400-$17FF: player 2's maze while player 1 plays (stage 78a)",
          "        self.title = [0] * 0x400         # $1C00-$1FFF: the title screen (stage 78a)",
          "",
          "    def load(self, mem):",
          "        for name, addr, n in FIELDS:",
          "            setattr(self, name, mem[addr] if n == 1 else list(mem[addr:addr + n]))",
          "        self.maze = list(mem[0x0C00:0x1000])",
          "        self.status = list(mem[0x2000:0x2050])",
          "        self.shadow = list(mem[0x0200:0x0300])",
          "        self.stick = list(mem[0x0278:0x027C])",
          "        self.collide = list(mem[0xD000:0xD010])",
          "        self.pokey = []",
          "        self.pm = list(mem[0x2300:0x2800])",
          "        self.hpos = list(mem[0xD000:0xD008])",
          "        self.picbuf = list(mem[0x0400:0x0420])",
          "        self.maze_orig = list(mem[0x0800:0x0C00])",
          "        self.saved1 = list(mem[0x1000:0x1400])",
          "        self.saved2 = list(mem[0x1400:0x1800])",
          "        self.title = list(mem[0x1C00:0x2000])",
          "        return self",
          "",
          "    def store(self, mem):",
          "        for name, addr, n in FIELDS:",
          "            v = getattr(self, name)",
          "            if n == 1:",
          "                mem[addr] = v & 0xFF",
          "            else:",
          "                for k in range(n):",
          "                    mem[addr + k] = v[k] & 0xFF",
          "        mem[0x0C00:0x1000] = bytes(b & 0xFF for b in self.maze)",
          "        mem[0x2000:0x2050] = bytes(b & 0xFF for b in self.status)",
          "        mem[0x0200:0x0300] = bytes(b & 0xFF for b in self.shadow)",
          "        mem[0x0278:0x027C] = bytes(b & 0xFF for b in self.stick)",
          "        mem[0x2300:0x2800] = bytes(b & 0xFF for b in self.pm)",
          "        mem[0xD000:0xD008] = bytes(b & 0xFF for b in self.hpos)",
          "        mem[0x0400:0x0420] = bytes(b & 0xFF for b in self.picbuf)",
          "        mem[0x0800:0x0C00] = bytes(b & 0xFF for b in self.maze_orig)",
          "        mem[0x1000:0x1400] = bytes(b & 0xFF for b in self.saved1)",
          "        mem[0x1400:0x1800] = bytes(b & 0xFF for b in self.saved2)",
          "        mem[0x1C00:0x2000] = bytes(b & 0xFF for b in self.title)",
          "",
          "    def zero_page(self):",
          "        mem = bytearray(0x10000)",
          "        self.store(mem)",
          "        return bytes(mem[:0x100])",
          ""]
    with open(os.path.join(HERE, "core_world.py"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print("wrote tools/core_world.py,", len(F), "fields")


if __name__ == "__main__":
    main()
