"""Stage 94: writes src/c/core/constants.h, the named constants of the original (docs/31 section 2: tools/analyze_constants.py NAMED) as C macros with their meaning, the routines that use them and the chapters that explain them.
The values are the immediate operands the ROM's routines use (checked against the ROM by tests/test_constants.py); this file only gives them their names in C.  The port's own constants (`SCORE_CELL_P1`, `KL_CONSOL_START`, ...) stay in the headers of the modules that use them.
Usage: python -I tools/make_c_constants.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import analyze_constants as C  # noqa: E402


def text():
    L = ["/* GENERATED by tools/make_c_constants.py (stage 94): the named constants of the original (docs/31 section 2).  Do not edit.  The values are immediate operands of the ROM's routines; each line says what the value is,",
         " * which routines use it and which chapters explain it.  Contains no table and no byte of the ROM data. */",
         "#ifndef PM_CORE_CONSTANTS_H",
         "#define PM_CORE_CONSTANTS_H",
         ""]
    w = max(len(n) for n, v, m, r, ch in C.NAMED)
    for n, v, m, r, ch in C.NAMED:
        L.append("#define %s %d%s/* $%02X: %s (%s; docs %s) */" % (n, v, " " * (w - len(n) + 5 - len(str(v))), v, m.replace("*/", "* /"), ", ".join(r), ch))
    L += ["", "#define PM_NAMED_CONSTANTS %d" % len(C.NAMED), "", "#endif", ""]
    return "\n".join(L)


def main():
    p = os.path.join(ROOT, "src", "c", "core", "constants.h")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text())
    print("wrote src/c/core/constants.h:", len(C.NAMED), "constants")


if __name__ == "__main__":
    main()
